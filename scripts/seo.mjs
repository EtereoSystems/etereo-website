/**
 * Generates public/robots.txt, public/sitemap.xml and public/llms.txt from the
 * single VITE_SITE_URL value (see .env). Runs automatically before `dev` and
 * `build` (see package.json), so these files always match the configured domain.
 *
 *   node scripts/seo.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { POSTS } from "./blog-posts.mjs";
import { SERVICES } from "./services.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const pub = resolve(root, "public");

// ── resolve the domain (env → .env file → default), no trailing slash ──────────
function readEnvFile() {
  const p = resolve(root, ".env");
  if (!existsSync(p)) return {};
  const out = {};
  for (const line of readFileSync(p, "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
  return out;
}
const env = readEnvFile();
const SITE_URL = (process.env.VITE_SITE_URL || env.VITE_SITE_URL || "https://www.etereo.sk").replace(/\/+$/, "");
const today = new Date().toISOString().slice(0, 10);

if (!existsSync(pub)) mkdirSync(pub, { recursive: true });

// ── robots.txt ─────────────────────────────────────────────────────────────────
// We WELCOME AI crawlers: the site should be quotable by ChatGPT, Claude,
// Perplexity, Google AI, Apple, etc. Explicit Allow blocks signal that intent.
const AI_AGENTS = [
  "GPTBot", "OAI-SearchBot", "ChatGPT-User",          // OpenAI
  "ClaudeBot", "Claude-SearchBot", "Claude-User", "anthropic-ai", // Anthropic
  "PerplexityBot", "Perplexity-User",                  // Perplexity
  "Google-Extended",                                   // Google AI
  "Applebot", "Applebot-Extended",                     // Apple
  "Amazonbot",                                         // Amazon
  "meta-externalagent",                                // Meta
  "CCBot",                                             // Common Crawl
  "cohere-ai",                                         // Cohere
  "DuckAssistBot",                                     // DuckDuckGo
  "MistralAI-User",                                    // Mistral
];

const robots = `# robots.txt — ${SITE_URL}
# Generated by scripts/seo.mjs. Edit .env (VITE_SITE_URL), not this file.

# Search + AI crawlers are welcome to index and cite this site.
User-agent: *
Allow: /

${AI_AGENTS.map((a) => `User-agent: ${a}\nAllow: /`).join("\n\n")}

Sitemap: ${SITE_URL}/sitemap.xml
`;
writeFileSync(resolve(pub, "robots.txt"), robots);

// ── sitemap.xml (single-page site with EN + SK variants) ─────────────────────────
const paths = [
  { path: "/", priority: "1.0" },
  { path: "/projects/", priority: "0.8" },
  { path: "/about/", priority: "0.8" },
  // the five service detail pages — primary commercial landing pages
  ...SERVICES.map((s) => ({ path: `/services/${s.slug}/`, priority: "0.9" })),
  { path: "/blog/", priority: "0.7" },
  // one clean-path entry per blog article (both EN and SK variants added below)
  ...POSTS.map((p) => ({ path: `/blog/${p.slug}/`, priority: "0.6" })),
];
// every page ships an EN and an SK variant; SK ranks a notch below its EN twin
const pages = paths.flatMap(({ path, priority }) => [
  { loc: `${SITE_URL}${path}`, path, priority },
  { loc: `${SITE_URL}${path}?lang=sk`, path, priority: (Number(priority) - 0.1).toFixed(1) },
]);
const alt = (path) => `    <xhtml:link rel="alternate" hreflang="en" href="${SITE_URL}${path}"/>
    <xhtml:link rel="alternate" hreflang="sk" href="${SITE_URL}${path}?lang=sk"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE_URL}${path}"/>`;
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${pages
  .map(
    (p) => `  <url>
    <loc>${p.loc}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>weekly</changefreq>
    <priority>${p.priority}</priority>
${alt(p.path)}
  </url>`
  )
  .join("\n")}
</urlset>
`;
writeFileSync(resolve(pub, "sitemap.xml"), sitemap);

